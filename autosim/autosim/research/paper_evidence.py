def _finite(value):
    return type(value) in (int, float) and math.isfinite(value)


def _values(measurement):
    reading = measurement.get('metric_reading') or {}
    values = reading.get('episode_values')
    if not isinstance(values, list) or not 1 <= len(values) <= 100000 or any(not _finite(x) for x in values):
        return None
    return list(values)


def _paired_values(left, right):
    """Episode indexes/shared seeds are NOT evidence of shared initial states."""
    lread, rread = left.get('metric_reading') or {}, right.get('metric_reading') or {}
    lm, rm = left.get('metric') or {}, right.get('metric') or {}
    column = lm.get('initial_state_hash_column')
    if not column or column != rm.get('initial_state_hash_column'):
        return None
    lk, rk = lread.get('episode_keys'), rread.get('episode_keys')
    lv, rv = _values(left), _values(right)
    if (not isinstance(lk,list) or not isinstance(rk,list) or lv is None or rv is None
            or len(lk)!=len(lv) or len(rk)!=len(rv) or len(set(map(str,lk)))!=len(lk)
            or set(map(str,lk))!=set(map(str,rk))):
        return None
    # Keys generated by MetricSpec include the declared native initial-state digest.
    import re
    if any(not isinstance(k,str) or not any(re.fullmatch(r'[a-fA-F0-9]{64}', p)
            for p in k.split('\x1f')) for k in [*lk,*rk]):
        return None
    aligned = dict(zip(rk,rv))
    return lv,[aligned[k] for k in lk]


def _costs(output):
    """Whole-run costs, not falsely allocated to individual experimental arms."""
    result = {'scope':'entire development run; not per-arm cost or equal-compute certification'}
    for name,key,field in [('task_gpu_budget.json','gpu_lease_hours','charged_seconds'),
                           ('budget.json','elapsed_wall_hours','elapsed_wall_seconds')]:
        path=output/name
        if path.is_file() and not path.is_symlink():
            row=read_json(path);value=row.get(field)
            result[key]=value/3600 if _finite(value) and value>=0 else None
            if name == 'task_gpu_budget.json':
                leases = row.get('leases') or {}
                result['gpu_cost_complete'] = all(lease.get('status') == 'finished'
                    for lease in leases.values())
    ledger=output/'agent/cost_ledger.json'
    if ledger.is_file() and not ledger.is_symlink():
        entries=read_json(ledger).get('entries') or []
        settled=[row.get('actual_usd') for row in entries if row.get('status')=='settled']
        valid=all(_finite(value) and value>=0 for value in settled)
        result['model_settled_usd']=sum(settled) if valid else None
        result['unknown_usage_entries']=sum(row.get('status')=='unknown' for row in entries)
        result['pending_entries']=sum(row.get('status')=='reserved' for row in entries)
        result['model_cost_complete']=valid and result['unknown_usage_entries']==result['pending_entries']==0
    interventions=output/'OPERATOR_INTERVENTIONS.md'
    result['operator_intervention_recorded']=interventions.is_file() and not interventions.is_symlink()
    result['autonomy_status']='development_operator_interventions' if result['operator_intervention_recorded'] else 'not_audited'
    return result


def build(output: Path, repo: Path, *, run_id='derived'):
    output,repo=Path(output).resolve(),Path(repo).resolve()
    run_id=_id(run_id)
    campaigns=view(output,run_id)
    rows,issues,comparisons=[],[],[]
    checked={}
    from .data_versions import resolve
    for campaign in campaigns:
        if campaign.get('status')=='evidence_unavailable':
            issues.append({'campaign':campaign['id'],'why':'campaign evidence unavailable'})
            continue
        accepted={}
        for arm in campaign['observations']:
            if arm.get('status') in {'unsupported','budget_limited'}:
                issues.append({'campaign':campaign['id'],'arm':arm['arm'],'seed':arm['seed'],
                               'why':arm.get('reason'),'status':arm['status']})
                continue
            try:
                measurement,witness=_measurement(output,run_id,arm['measurement_label'])
                receipt=verify_measurement(output/'research'/run_id,arm['measurement_label'])
                if receipt.get('status')!='consistent':
                    raise ValueError('native measurement receipt/identity is not consistently verified')
                for ident in (arm['acquired_version_id'],arm['training_version_id']):
                    if ident is None:
                        continue  # A fixed-data control has no newly acquired version.
                    if ident not in checked:
                        _,bindings=resolve(output,repo,{'data':'data-version:'+ident})
                        checked[ident]=bindings[0]
                consumed=measurement.get('data_consumption') or {}
                if consumed.get('status')!='verified' or arm['training_version_id'] not in consumed.get('versions',[]):
                    raise ValueError('registered training version was not consumed')
                rows.append({'campaign':campaign['id'],**arm,'measurement_sha256':witness['sha256'],
                    'metric_name':(measurement.get('metric') or {}).get('name'),
                    'direction':(measurement.get('metric') or {}).get('direction'),
                    'evaluation_episodes':(measurement.get('metric_reading') or {}).get('samples'),
                    'phase':'development','formal_paper_eligible':False})
                accepted[(arm['arm'],arm['seed'])]=measurement
            except (OSError,ValueError,TypeError,KeyError) as exc:
                issues.append({'campaign':campaign['id'],'arm':arm['arm'],'seed':arm['seed'],'why':str(exc)[:500]})
        pairs = ([('random','targeted')] if campaign.get('schema_version',1) == 1 else
                 [('random_quality','agent_targeted'), ('rule_targeted','agent_targeted'),
                  ('targeted_quality','fdas'), ('fixed_continuation','random_quality')])
        for seed, (left_arm, right_arm) in itertools.product(campaign['comparison']['seeds'], pairs):
            targeted=accepted.get((right_arm,seed));random=accepted.get((left_arm,seed))
            if not targeted or not random:
                continue
            tm,rm=targeted.get('metric') or {},random.get('metric') or {}
            fields=('name','direction','unit','aggregation')
            if any(tm.get(k)!=rm.get(k) for k in fields):
                issues.append({'campaign':campaign['id'],'seed':seed,'why':'metric semantics differ across arms'})
                continue
            from .significance import compare
            paired=_paired_values(random,targeted)
            left,right=paired if paired is not None else (_values(random),_values(targeted))
            if left is None or right is None:
                comparisons.append({'campaign':campaign['id'],'seed':seed,'status':'episode_statistics_unavailable'})
                continue
            kind='binary' if all(x in (0,1) for x in [*left,*right]) else 'continuous'
            result=compare(left,right,kind=kind,paired=paired is not None).as_dict()
            comparisons.append({'campaign':campaign['id'],'seed':seed,
                'left_method':left_arm,'right_method':right_arm,
                ('random_to_targeted' if left_arm == 'random' else 'statistics'):result,
                'paired_by_initial_state_hash':paired is not None,
                'interpretation':'development episode difference only; not held-out, causal fairness or training-seed uncertainty'})
    seed_summaries=[]
    for campaign in campaigns:
        for arm in campaign.get('comparison', {}).get('arms', []):
            selected=[row for row in rows if row['campaign']==campaign['id'] and row['arm']==arm]
            values=[row['metric_value'] for row in selected]
            if values:
                seed_summaries.append({'campaign':campaign['id'],'arm':arm,'training_seed_count':len(values),
                    'mean':statistics.mean(values),'sample_std':statistics.stdev(values) if len(values)>1 else None,
                    'interpretation':'descriptive across declared seed IDs; actual seed use still needs audit; no pooled-episode training-seed CI'})
    result={'schema_version':1,'phase':'development','formal_paper_eligible':False,
            'rows':rows,'comparisons':comparisons,'seed_summaries':seed_summaries,
            'costs':_costs(output),'issues':issues,
            'pending_campaigns':[{'id':c['id'],'planned_arms':(c.get('comparison') or {}).get('arms'),
                                 'observed_arms':len(c['observations'])} for c in campaigns],
            'limitations':['Formal tables require frozen harness/skills, preregistered protocols and independent held-out runs.',
                           'Episode-level CIs do not quantify variability across independently trained policies.',
                           'Run-level cost must not be labelled per-arm or used as proof of equal-compute comparisons.']}
    result['snapshot_id']=object_digest(result)
    return result


def markdown(report):
    def cell(value):
        return str(value if value is not None else '未知').replace('|','\\|').replace('\n',' ')
    lines=['# FDAS 数据研究证据表','',
           '这是开发证据导出，不是正式论文主表。只展示经原生回执复验及当前数据身份核验的测量。','',
           '| 实验 | 方法 | 声明种子 | 新数据视图 episode | 实际消费版本 | 开发指标 |','| --- | --- | ---: | ---: | --- | ---: |']
    for row in report['rows']:
        lines.append('| '+' | '.join(cell(row.get(k)) for k in (
            'campaign','arm','seed','reported_full_episodes','training_version_id','metric_value'))+' |')
    if not report['rows']:
        lines+=['','尚无符合导出合同的数据实验结果。待执行不是零分。']
    lines+=['','## 成本与人工干预','',*['- '+cell(k)+'：'+cell(v) for k,v in report['costs'].items()],
            '','## 尚缺的证据','',*['- '+cell(row) for row in report['issues']],
            *['- '+line for line in report['limitations']], '']
    return '\n'.join(lines)
