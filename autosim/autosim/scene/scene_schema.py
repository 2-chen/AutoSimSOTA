TEMPLATES = {
    "single_object_grasp": template_single_object_grasp,
    "pick_and_place": template_pick_and_place,
    "stack_blocks": template_stack_blocks,
    "peg_insertion": template_peg_insertion,
    "bin_picking": template_bin_picking,
    "empty_workspace": template_empty_workspace,
}


def list_templates() -> List[str]:
    """List available scene template names."""
    return list(TEMPLATES.keys())


def get_template(name: str) -> StructuredSceneConfig:
    """Get a scene template by name."""
    fn = TEMPLATES.get(name)
    if fn is None:
        raise KeyError(f"Unknown template: {name}. Available: {list_templates()}")
    return fn()


def apply_variation(config: StructuredSceneConfig, seed: int = 0,
                    variation_scale: float = 0.1) -> StructuredSceneConfig:
    """Apply random pose variation to objects in a scene config."""
    import numpy as np
    rng = np.random.RandomState(seed)

    varied = StructuredSceneConfig.from_dict(config.to_dict())

    for obj in varied.objects:
        if obj.mass > 0:  # only movable objects
            obj.position[0] += rng.uniform(-variation_scale, variation_scale)
            obj.position[1] += rng.uniform(-variation_scale, variation_scale)
            if obj.position[2] > 0.05:  # don't move through table
                obj.position[2] += rng.uniform(-variation_scale * 0.5, variation_scale * 0.5)

    return varied
