def template_bin_picking() -> StructuredSceneConfig:
    """Bin picking: multiple objects scattered in a bin."""
    rng = __import__("numpy").random.RandomState(42)
    objects = []
    for i in range(5):
        objects.append(ObjectConfig(
            name=f"part_{i}",
            shape="Cube",
            position=[0.5 + rng.uniform(-0.1, 0.1),
                      0.0 + rng.uniform(-0.08, 0.08),
                      0.42 + i * 0.005],
            scale=[0.025, 0.025, 0.025],
            color=[rng.uniform(0.2, 0.9), rng.uniform(0.2, 0.9), rng.uniform(0.2, 0.9)],
            mass=0.02,
            semantic_tag="grasp_target",
        ))

    return StructuredSceneConfig(
        name="bin_picking",
        description="Pick one of several small parts scattered on a table",
        table=TableConfig(),
        objects=objects,
        robots=[RobotPlacement(model="franka", position=[0.0, 0.0, 0.75])],
        task=TaskDefinition(
            category="grasp",
            description="Grasp any one of the colored parts",
            success_criteria="any part lifted > 5cm",
            target_object="",
        ),
    )


