"""
Scene Schema — data model for representing Isaac Sim scenes.

A SceneConfig is a complete, structured representation of an Isaac Sim
scene that can be:
  1. Generated by an LLM from a natural language description
  2. Built in Isaac Sim via the MCP client
  3. Stored and retrieved from the scene registry
  4. Varied automatically for domain randomization

Scene configs are fully serializable to/from JSON/YAML.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import Any, Dict, List, Optional, Tuple


class ObjectShape(Enum):
    CUBE = "Cube"
    SPHERE = "Sphere"
    CYLINDER = "Cylinder"
    CAPSULE = "Capsule"
    CONE = "Cone"
    MESH = "Mesh"
    PLANE = "Plane"
    TORUS = "Torus"
    DISC = "Disc"


class RobotModel(Enum):
    FRANKA = "franka"
    UR5 = "ur5"
    UR10 = "ur10"


class TaskCategory(Enum):
    REACH = "reach"
    GRASP = "grasp"
    PICK_PLACE = "pick_place"
    INSERTION = "insertion"
    PUSH = "push"
    PULL = "pull"
    STACK = "stack"
    ASSEMBLY = "assembly"
    CUSTOM = "custom"


@dataclass
class ObjectConfig:
    """A single object in the scene."""
    name: str
    shape: str = "Cube"
    position: List[float] = field(default_factory=lambda: [0.5, 0.0, 0.3])
    scale: List[float] = field(default_factory=lambda: [0.05, 0.05, 0.05])
    color: List[float] = field(default_factory=lambda: [0.8, 0.2, 0.2])
    mass: float = 0.05
    collision: bool = True
    usd_path: str = ""
    material: str = ""
    friction: float = 0.5
    restitution: float = 0.1
    semantic_tag: str = ""  # e.g., "grasp_target", "obstacle", "container"
    visual_only: bool = False  # if True, no collision


@dataclass
class RobotPlacement:
    """A robot in the scene."""
    model: str = "franka"
    name: str = ""
    position: List[float] = field(default_factory=lambda: [0.0, 0.0, 0.0])
    orientation: List[float] = field(default_factory=lambda: [0.0, 0.0, 0.0, 1.0])
    home_joints: Optional[List[float]] = None
    gripper_open_on_start: bool = True


@dataclass
class LightingConfig:
    """Scene lighting setup."""
    style: str = "default"  # default, bright, dim, warm, cold, colorful
    intensity: float = 1.0
    num_lights: int = 2
    shadows: bool = True


@dataclass
class CameraSetup:
    """Camera placement."""
    position: List[float] = field(default_factory=lambda: [1.2, 0.5, 1.0])
    target: List[float] = field(default_factory=lambda: [0.3, 0.0, 0.3])
    fov: float = 60.0
    resolution: Tuple[int, int] = (1280, 720)


@dataclass
class TableConfig:
    """Optional table/workbench."""
    present: bool = True
    size: Tuple[float, float] = (0.8, 1.2)
    height: float = 0.75
    position: List[float] = field(default_factory=lambda: [0.5, 0.0, 0.375])
    color: List[float] = field(default_factory=lambda: [0.4, 0.4, 0.4])


@dataclass
class DomainRandomizationConfig:
    """Domain randomization settings."""
    enabled: bool = False
    lighting_variation: float = 0.3
    texture_variation: bool = False
    object_pose_jitter: float = 0.02
    joint_noise: float = 0.02
    num_random_objects: int = 0
    random_object_types: List[str] = field(default_factory=lambda: ["Cube", "Sphere"])


@dataclass
class TaskDefinition:
    """Definition of the task to perform in the scene."""
    category: str = "reach"
    description: str = "Move end-effector to target position"
    success_criteria: str = "distance < 5cm"
    target_object: str = ""  # name of target object in scene
    max_steps: int = 500
    variations: int = 1  # number of pose variations for evaluation


@dataclass
class StructuredSceneConfig:
    """
    Complete, structured scene configuration.

    This is the core data model that bridges LLM generation → Isaac Sim execution.
    Fully serializable to/from JSON.
    """
    name: str = "autosim_scene"
    description: str = ""

    # Environment
    floor: bool = True
    table: TableConfig = field(default_factory=TableConfig)
    lighting: LightingConfig = field(default_factory=LightingConfig)
    camera: CameraSetup = field(default_factory=CameraSetup)

    # Objects
    objects: List[ObjectConfig] = field(default_factory=list)

    # Robot(s)
    robots: List[RobotPlacement] = field(default_factory=lambda: [RobotPlacement()])

    # Physics
    gravity: List[float] = field(default_factory=lambda: [0.0, 0.0, -9.81])
    substeps: int = 2
    dt: float = 1.0 / 60.0

    # Task
    task: TaskDefinition = field(default_factory=TaskDefinition)

    # Domain randomization
    domain_rand: DomainRandomizationConfig = field(default_factory=DomainRandomizationConfig)

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dict (JSON-compatible)."""
        return json.loads(json.dumps(asdict(self), default=str))

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "StructuredSceneConfig":
        """Deserialize from dict."""
        return cls(
            name=data.get("name", "scene"),
            description=data.get("description", ""),
            floor=data.get("floor", True),
            table=TableConfig(**data.get("table", {})),
            lighting=LightingConfig(**data.get("lighting", {})),
            camera=CameraSetup(**data.get("camera", {})),
            objects=[ObjectConfig(**o) for o in data.get("objects", [])],
            robots=[RobotPlacement(**r) for r in data.get("robots", [])],
            gravity=data.get("gravity", [0, 0, -9.81]),
            substeps=data.get("substeps", 2),
            dt=data.get("dt", 1.0 / 60.0),
            task=TaskDefinition(**data.get("task", {})),
            domain_rand=DomainRandomizationConfig(**data.get("domain_rand", {})),
        )


